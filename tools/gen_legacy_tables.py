# -*- coding: utf-8 -*-
"""Generate src/lib/legacy-tables.js.

The WHATWG encoding standard (and therefore TextDecoder in Chrome) has no
ISO-8859-16 label, so we ship the 256 entry table ourselves.  The table is
emitted as code points indexed by byte value.
"""
import json
import os

TABLES = {
    "iso-8859-16": "iso8859_16",
}

out_dir = os.path.join("src", "lib")
os.makedirs(out_dir, exist_ok=True)
path = os.path.join(out_dir, "legacy-tables.js")

payload = {}
for name, codec in TABLES.items():
    chars = []
    for b in range(256):
        try:
            s = bytes([b]).decode(codec)
            chars.append(ord(s[0]))
        except UnicodeDecodeError:
            chars.append(0xFFFD)
    payload[name] = chars

with open(path, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/**\n")
    fh.write(" * Legacy single byte tables that the WHATWG encoding standard does not\n")
    fh.write(" * provide.  Generated by tools/gen_legacy_tables.py.\n")
    fh.write(" *\n")
    fh.write(" * Each table maps a byte value to its Unicode code point.\n")
    fh.write(" */\n")
    fh.write("(function (root) {\n")
    fh.write("  'use strict';\n")
    fh.write("  var CE = (root.CE = root.CE || {});\n")
    fh.write("  CE.legacyTables = ")
    fh.write(json.dumps(payload, separators=(",", ":")))
    fh.write(";\n")
    fh.write("})(typeof globalThis !== 'undefined' ? globalThis : self);\n")

print("wrote", path, os.path.getsize(path), "bytes")
